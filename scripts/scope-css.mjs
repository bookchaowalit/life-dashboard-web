#!/usr/bin/env node
/**
 * Scope a module's global stylesheet under `.m-<module>`.
 *
 *   node scripts/scope-css.mjs <module> <input.css> <output.css>
 *
 * Every selector gets the `.m-<module>` prefix; `:root`, `html` and `body`
 * become the module wrapper itself; `@keyframes` names are prefixed and
 * their `animation`/`animation-name` references rewritten. `@media` and
 * `@supports` blocks are scoped recursively. Comments are dropped.
 */
import { readFileSync, writeFileSync } from 'node:fs';

function splitTopLevel(text, separator) {
  const parts = [];
  let depth = 0;
  let current = '';
  for (const char of text) {
    if (char === '(' || char === '[') depth += 1;
    if (char === ')' || char === ']') depth -= 1;
    if (char === separator && depth === 0) {
      parts.push(current);
      current = '';
    } else {
      current += char;
    }
  }
  parts.push(current);
  return parts;
}

export function scopeSelector(selector, scope) {
  const trimmed = selector.trim();
  if (!trimmed) return trimmed;
  const root = trimmed.match(/^(:root|html|body)\b(.*)$/);
  if (root) {
    const rest = root[2].trim();
    return rest ? `${scope} ${rest}` : scope;
  }
  if (trimmed.startsWith('::selection')) return `${scope} ${trimmed}, ${scope}${trimmed}`;
  return `${scope} ${trimmed}`;
}

/** Parse `text` into top-level blocks: { prelude, body } where body is the raw inner text. */
function blocks(text) {
  const result = [];
  let index = 0;
  while (index < text.length) {
    const open = text.indexOf('{', index);
    if (open === -1) break;
    let depth = 1;
    let cursor = open + 1;
    while (cursor < text.length && depth > 0) {
      if (text[cursor] === '{') depth += 1;
      if (text[cursor] === '}') depth -= 1;
      cursor += 1;
    }
    result.push({ prelude: text.slice(index, open).trim(), body: text.slice(open + 1, cursor - 1) });
    index = cursor;
  }
  return result;
}

export function scopeCss(css, module) {
  const scope = `.m-${module}`;
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const keyframes = new Map();
  for (const match of clean.matchAll(/@keyframes\s+([\w-]+)/g)) keyframes.set(match[1], `m-${module}-${match[1]}`);

  const renameAnimations = (body) =>
    body.replace(/(animation(?:-name)?\s*:\s*)([^;}]+)/g, (_, head, value) =>
      head + value.replace(/[\w-]+/g, (word) => keyframes.get(word) ?? word));

  const render = (text) =>
    blocks(text).map(({ prelude, body }) => {
      if (prelude.startsWith('@keyframes')) {
        const name = prelude.replace(/@keyframes\s+/, '').trim();
        return `@keyframes ${keyframes.get(name) ?? name} {${body}}`;
      }
      if (prelude.startsWith('@media') || prelude.startsWith('@supports')) {
        return `${prelude} {\n${render(body)}\n}`;
      }
      if (prelude.startsWith('@')) {
        throw new Error(`unsupported at-rule in module CSS: ${prelude}`);
      }
      const selectors = splitTopLevel(prelude, ',').map((part) => scopeSelector(part, scope)).join(', ');
      return `${selectors} {${renameAnimations(body)}}`;
    }).join('\n');

  return `/* Generated by scripts/scope-css.mjs for module "${module}". Do not edit by hand. */\n${render(clean)}\n`;
}

if (process.argv[1]?.endsWith('scope-css.mjs')) {
  const [module, input, output] = process.argv.slice(2);
  if (module && input && output) {
    writeFileSync(output, scopeCss(readFileSync(input, 'utf8'), module));
  }
}
